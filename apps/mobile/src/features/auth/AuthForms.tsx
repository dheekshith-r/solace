import { useRouter } from 'expo-router';
import { useRef, useState, type ComponentRef } from 'react';
import { StyleSheet, TextInput, View } from 'react-native';
import { Button, Card, Checkbox, Entrance, Screen, Text, TextField } from '../../components';
import { ApiError, OFFLINE_MESSAGE, withQuietRetry } from '../../lib/http';
import { spacing } from '../../theme/tokens';
import { useOnboarding } from '../onboarding/store';
import { logIn, signUp } from './session';

type Field = ComponentRef<typeof TextInput>;

const GEMINI_NOTICE = "Sola's replies are generated by Google Gemini. Please avoid sharing sensitive personal details in this demo.";
const STILL_TRYING = 'Solace is waking up. Still trying…';

export const emailLooksValid = (email: string) => /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email.trim());

export function signUpErrors(values: { name: string; email: string; password: string; adult: boolean }) {
  return {
    name: values.name.trim() ? undefined : 'Tell Sola what to call you.',
    email: emailLooksValid(values.email) ? undefined : 'Enter an email address like name@example.com.',
    password: values.password.length >= 8 ? undefined : 'Use 8 or more characters.',
    adult: values.adult ? undefined : 'You must be 18 or older to use Solace.',
  };
}

function Banner({ message }: { message: string }) {
  return (
    <Card>
      <Text variant="callout" accessibilityLiveRegion="polite" accessibilityRole="alert">
        {message}
      </Text>
    </Card>
  );
}

function deviceTimeZone(): string | undefined {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone;
  } catch {
    return undefined;
  }
}

export function SignUpScreen() {
  const router = useRouter();
  const { goal, reminders } = useOnboarding();
  const [name, setName] = useState('');
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [adult, setAdult] = useState(false);
  const [tried, setTried] = useState(false);
  const [busy, setBusy] = useState(false);
  const [banner, setBanner] = useState<string | null>(null);
  const [serverEmailError, setServerEmailError] = useState<string | undefined>();
  const emailRef = useRef<Field>(null);
  const passwordRef = useRef<Field>(null);

  const errors = signUpErrors({ name, email, password, adult });
  const show = (message?: string) => (tried ? message : undefined);

  const submit = async () => {
    setTried(true);
    setServerEmailError(undefined);
    if (Object.values(errors).some(Boolean)) return;
    setBusy(true);
    setBanner(null);
    try {
      const timezone = deviceTimeZone();
      await withQuietRetry(
        () =>
          signUp({
            name: name.trim(),
            email: email.trim(),
            password,
            isAdult: true,
            ...(goal ? { goal } : null),
            ...(timezone ? { timezone } : null),
            reminders,
          }),
        () => setBanner(STILL_TRYING),
      );
      router.replace('/today');
    } catch (error) {
      if (error instanceof ApiError && error.status === 409) setServerEmailError('An account with this email already exists. Log in instead.');
      else setBanner(error instanceof ApiError ? error.message : OFFLINE_MESSAGE);
    } finally {
      setBusy(false);
    }
  };

  return (
    <Screen title="Create your account" keyboard>
      <Entrance index={0} style={styles.form}>
        <TextField label="Name" value={name} onChangeText={setName} placeholder="What should Sola call you?" autoComplete="name" textContentType="name" returnKeyType="next" onSubmitEditing={() => emailRef.current?.focus()} submitBehavior="submit" error={show(errors.name)} />
        <TextField ref={emailRef} label="Email" value={email} onChangeText={setEmail} placeholder="you@example.com" keyboardType="email-address" autoCapitalize="none" autoComplete="email" textContentType="emailAddress" returnKeyType="next" onSubmitEditing={() => passwordRef.current?.focus()} submitBehavior="submit" error={serverEmailError ?? show(errors.email)} />
        <TextField ref={passwordRef} label="Password" value={password} onChangeText={setPassword} secure placeholder="At least 8 characters" autoComplete="new-password" textContentType="newPassword" returnKeyType="done" onSubmitEditing={() => void submit()} error={show(errors.password)} helper="Use 8 or more characters." />
      </Entrance>
      <Entrance index={1} style={styles.form}>
        <View style={styles.adult}>
          <Checkbox checked={adult} onChange={setAdult} accessibilityLabel="I'm 18 or older" label={<Text variant="callout">I&apos;m 18 or older</Text>} />
          {show(errors.adult) ? (
            <Text variant="footnoteStrong" accessibilityLiveRegion="polite">
              {errors.adult}
            </Text>
          ) : null}
        </View>
        <Text variant="footnote" tone="muted">
          {GEMINI_NOTICE}
        </Text>
        {banner ? <Banner message={banner} /> : null}
        <Button label="Create account" onPress={() => void submit()} loading={busy} disabled={!adult} wide accessibilityHint={adult ? undefined : 'Confirm you are 18 or older first.'} />
        <Button label="I already have an account" variant="text" align="center" onPress={() => router.replace('/log-in')} />
      </Entrance>
    </Screen>
  );
}

export function LogInScreen() {
  const router = useRouter();
  const [email, setEmail] = useState('');
  const [password, setPassword] = useState('');
  const [tried, setTried] = useState(false);
  const [busy, setBusy] = useState(false);
  const [banner, setBanner] = useState<string | null>(null);
  const [wrong, setWrong] = useState<string | undefined>();
  const passwordRef = useRef<Field>(null);

  const emailError = tried && !emailLooksValid(email) ? 'Enter an email address like name@example.com.' : undefined;
  const passwordError = tried && !password ? 'Enter your password.' : undefined;

  const submit = async () => {
    setTried(true);
    setWrong(undefined);
    if (!emailLooksValid(email) || !password) return;
    setBusy(true);
    setBanner(null);
    try {
      await withQuietRetry(() => logIn({ email: email.trim(), password }), () => setBanner(STILL_TRYING));
      useOnboarding.getState().finish(true);
      router.replace('/today');
    } catch (error) {
      if (error instanceof ApiError && error.status === 401) setWrong("That email and password don't match. Try again.");
      else setBanner(error instanceof ApiError ? error.message : OFFLINE_MESSAGE);
    } finally {
      setBusy(false);
    }
  };

  return (
    <Screen title="Welcome back" keyboard>
      <Entrance index={0} style={styles.form}>
        <TextField label="Email" value={email} onChangeText={setEmail} placeholder="you@example.com" keyboardType="email-address" autoCapitalize="none" autoComplete="email" textContentType="emailAddress" returnKeyType="next" onSubmitEditing={() => passwordRef.current?.focus()} submitBehavior="submit" error={emailError} />
        <TextField ref={passwordRef} label="Password" value={password} onChangeText={setPassword} secure autoComplete="current-password" textContentType="password" returnKeyType="done" onSubmitEditing={() => void submit()} error={wrong ?? passwordError} />
      </Entrance>
      <Entrance index={1} style={styles.form}>
        {banner ? <Banner message={banner} /> : null}
        <Button label="Log in" onPress={() => void submit()} loading={busy} wide />
        <Button label="Create an account" variant="text" align="center" onPress={() => router.replace('/sign-up')} />
      </Entrance>
    </Screen>
  );
}

const styles = StyleSheet.create({
  form: { gap: spacing.lg },
  adult: { gap: spacing.xs },
});
