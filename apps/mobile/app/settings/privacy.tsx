// Privacy and data (spec 8.9): personalize, delete all chats, delete the account. Clear words, typed confirm.
import { updateMeResponseSchema } from '@solace/shared';
import { useRouter } from 'expo-router';
import { Trash2, UserX } from 'lucide-react-native';
import { useState } from 'react';
import { Alert, StyleSheet, View } from 'react-native';
import { Button, Card, Entrance, ListGroup, ListRow, Screen, Text, TextField, useTheme, useToast } from '../../src/components';
import { authed, logOut, useSession } from '../../src/features/auth/session';
import { CONVERSATIONS_KEY } from '../../src/features/chat/data';
import { queryClient } from '../../src/lib/queryClient';
import { spacing } from '../../src/theme/tokens';

const CONFIRM_WORD = 'DELETE';

export default function PrivacyScreen() {
  const router = useRouter();
  const toast = useToast();
  const { palette } = useTheme();
  const user = useSession((s) => s.user);
  const [confirm, setConfirm] = useState('');
  const [deleting, setDeleting] = useState(false);

  const setPersonalize = async (on: boolean) => {
    if (!user) return;
    useSession.setState({ user: { ...user, personalize: on } });
    try {
      const res = await authed('/me', { method: 'PATCH', body: { personalize: on }, schema: updateMeResponseSchema });
      useSession.setState({ user: res.user });
    } catch {
      useSession.setState({ user });
      toast.show("Couldn't save that. Try again.");
    }
  };

  const deleteChats = () =>
    Alert.alert('Delete all chats?', 'Every conversation with Sola will be gone for good.', [
      { text: 'Cancel', style: 'cancel' },
      {
        text: 'Delete all',
        style: 'destructive',
        onPress: async () => {
          try {
            await authed('/conversations', { method: 'DELETE' });
            await queryClient.invalidateQueries({ queryKey: CONVERSATIONS_KEY });
            toast.show('All chats deleted.');
          } catch {
            toast.show("Couldn't delete chats. Check your connection.");
          }
        },
      },
    ]);

  const deleteAccount = async () => {
    setDeleting(true);
    try {
      await authed('/me', { method: 'DELETE' });
      await logOut();
      router.replace('/onboarding');
    } catch {
      toast.show("Couldn't delete your account. Check your connection.");
      setDeleting(false);
    }
  };

  return (
    <Screen title="Privacy and data" back keyboard>
      <Entrance index={0}>
        <ListGroup>
          <ListRow
            title="Personalize with my history"
            subtitle="Sola uses your recent moods and chats to make replies and suggestions fit you. Off: Sola only sees the current conversation."
            trailing={{ kind: 'switch', on: user?.personalize ?? true, onChange: (on) => void setPersonalize(on) }}
          />
        </ListGroup>
      </Entrance>
      <Entrance index={1}>
        <ListGroup>
          <ListRow icon={Trash2} title="Delete all chats" destructive trailing={{ kind: 'none' }} onPress={deleteChats} />
        </ListGroup>
      </Entrance>
      <Entrance index={2}>
        <Card>
          <View style={styles.danger}>
            <UserX size={spacing.xxl} color={palette.destructive} />
            <Text variant="heading">Delete your account</Text>
          </View>
          <Text variant="callout" tone="muted">
            Your account, moods, chats and settings are deleted from Solace for good. This can&apos;t be undone.
          </Text>
          <TextField label={`Type ${CONFIRM_WORD} to confirm`} value={confirm} onChangeText={setConfirm} autoCapitalize="characters" autoCorrect={false} />
          <Button label="Delete my account" onPress={() => void deleteAccount()} loading={deleting} disabled={confirm.trim() !== CONFIRM_WORD} wide />
        </Card>
      </Entrance>
      <Entrance index={3}>
        <Text variant="footnote" tone="muted">
          Sola&apos;s replies are generated by Google Gemini. Please avoid sharing sensitive personal details in this demo. Solace is not a substitute for professional help.
        </Text>
      </Entrance>
    </Screen>
  );
}

const styles = StyleSheet.create({ danger: { flexDirection: 'row', alignItems: 'center', gap: spacing.sm } });
